def exponential_of_numbers(base, exponent):
    return base ** exponent

def addition_of_numbers(number1, number2):
    return number1 + number2

def subtraction_of_numbers(number1, number2):
    return number1 - number2

def multiplication_of_numbers(number1, number2):
    return number1 * number2

def division_of_numbers(dividend, divisor):
    return dividend / divisor


print(exponential_of_numbers(2, 3))

print(addition_of_numbers(23, 23))

print(subtraction_of_numbers(5, 3))

print(multiplication_of_numbers(23, 2))

print(division_of_numbers(6, 3))
